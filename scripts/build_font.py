#!/usr/bin/env python3
"""Build shared 4-bit grayscale display glyphs from the pinned Inter font."""
from pathlib import Path
from math import floor,ceil
import hashlib,json,shutil
from PIL import Image,ImageDraw,ImageFont
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'assets/fonts/InterVariable.ttf'
# Rasterize on the target pixel grid. Upsampling before font hinting and then
# shrinking it made 10-pixel labels unnecessarily soft on this small panel.
SS=1

def build(size,weight,characters):
    font=ImageFont.truetype(str(SOURCE),size*SS)
    font.set_variation_by_axes([14,weight])
    features=['tnum']
    cap=ceil(-font.getbbox('H',anchor='ls',features=features)[1]/SS)
    data=bytearray();glyphs={}
    for c in characters:
        left,top,right,bottom=font.getbbox(c,anchor='ls',features=features)
        x,y=floor(left/SS),floor(top/SS)
        width,height=ceil(right/SS)-x,ceil(bottom/SS)-y
        advance=max(1,round(font.getlength(c,features=features)/SS))
        offset=len(data)
        if width and height:
            canvas=Image.new('L',(width*SS,height*SS))
            ImageDraw.Draw(canvas).text((-x*SS,-y*SS),c,font=font,fill=255,anchor='ls',features=features)
            mask=canvas.resize((width,height),Image.Resampling.LANCZOS)
            pixels=[min(15,(value*15+127)//255) for value in mask.get_flattened_data()]
            if len(pixels)%2:pixels.append(0)
            data.extend((pixels[i]<<4)|pixels[i+1] for i in range(0,len(pixels),2))
        glyphs[c]={'offset':offset,'width':width,'height':height,'x':x,'y':y+cap,'advance':advance}
    return {'size':size,'weight':weight,'glyphs':glyphs,'data':list(data)}

characters=''.join(chr(i) for i in range(32,127))
fonts={'compact':build(10,700,characters),'small':build(11,700,characters),'large':build(27,600,' 0123456789:?-BT')}
lines=['/* Generated by scripts/build_font.py from Inter, Copyright (c) 2016 The Inter Project Authors.','   Glyph data is licensed under SIL OFL 1.1; see font-license.txt. */','#ifndef F75_FONT_DATA_H','#define F75_FONT_DATA_H','#include <stdint.h>','typedef struct { uint16_t offset; uint8_t width,height; int8_t x,y; uint8_t advance; } f75_glyph;']
for name,font in fonts.items():
    lines.append(f'static const f75_glyph f75_font_{name}[128]={{')
    for c,g in font['glyphs'].items():lines.append(f'[{ord(c)}]={{{g["offset"]},{g["width"]},{g["height"]},{g["x"]},{g["y"]},{g["advance"]}}},')
    lines.append('};')
    lines.append(f'static const uint8_t f75_font_{name}_pixels[]={{')
    data=font['data']
    lines.extend(','.join(hex(v) for v in data[i:i+32])+',' for i in range(0,len(data),32))
    lines.append('};')
lines.append('#endif')
(ROOT/'firmware/font_data.h').write_text('\n'.join(lines)+'\n')
(ROOT/'ui/font.js').write_text('// Generated by scripts/build_font.py. Inter glyph data: SIL OFL 1.1; see assets/font-license.txt.\nwindow.F75_FONT='+json.dumps(fonts,separators=(',',':'))+';\n')
shutil.copyfile(ROOT/'assets/fonts/OFL.txt',ROOT/'firmware/font-license.txt')
shutil.copyfile(ROOT/'assets/fonts/OFL.txt',ROOT/'ui/assets/font-license.txt')
manifest={'font':'Inter','weight':700,'optical_size':14,'coverage_bits':4,'supersampling':SS,'source_sha256':hashlib.sha256(SOURCE.read_bytes()).hexdigest(),'fonts':{name:{'size':font['size'],'weight':font['weight'],'glyphs':len(font['glyphs']),'pixel_bytes':len(font['data'])} for name,font in fonts.items()},'pixel_bytes':sum(len(f['data']) for f in fonts.values()),'compiler':'scripts/build_font.py'}
(ROOT/'assets/fonts/manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
print(json.dumps(manifest))
