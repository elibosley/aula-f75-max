#!/usr/bin/env python3
"""Compile the generated 3x2 atlas into a transparent 4-bit C sprite set."""
from pathlib import Path
import hashlib,json
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
source=ROOT/'assets/chibi/chibi-atlas-original.png'
im=Image.open(source).convert('RGBA');w,h=im.size
assert w%3==0 and h%2==0 and w//3==h//2
frames=[im.crop((x*w//3,y*h//2,(x+1)*w//3,(y+1)*h//2)).resize((64,64),Image.Resampling.LANCZOS) for y in range(2) for x in range(3)]
native_frames=[im.crop((x*w//3,y*h//2,(x+1)*w//3,(y+1)*h//2)).resize((80,80),Image.Resampling.LANCZOS) for y in range(2) for x in range(3)]
opaque=[p[:3] for frame in frames for p in frame.get_flattened_data() if p[3]>=128]
samples=Image.new('RGB',(len(opaque),1));samples.putdata(opaque)
quantized=samples.quantize(colors=15,method=Image.Quantize.MEDIANCUT,dither=Image.Dither.NONE)
raw=quantized.getpalette();palette=[tuple(raw[i:i+3]) for i in range(0,45,3)]
def index(pixel):
 if pixel[3]<128:return 0
 return 1+min(range(15),key=lambda i:sum((pixel[j]-palette[i][j])**2 for j in range(3)))
rgb565=[0]+[((r>>3)<<11)|((g>>2)<<5)|(b>>3) for r,g,b in palette]
packed=[];atlas=Image.new('RGBA',(192,128))
for n,frame in enumerate(frames):
 indices=[index(p) for p in frame.get_flattened_data()]
 packed.append(bytes((indices[i]<<4)|indices[i+1] for i in range(0,len(indices),2)))
 preview=Image.new('RGBA',(64,64));preview.putdata([(0,0,0,0) if i==0 else (*palette[i-1],255) for i in indices]);atlas.paste(preview,((n%3)*64,(n//3)*64))
atlas.save(ROOT/'ui/assets/chibi-sprites.png')
lines=['/* Generated by scripts/build_pet_assets.py; transparent index 0, six 64x64 frames. */','#ifndef F75_PET_ASSETS_H','#define F75_PET_ASSETS_H','#include <stdint.h>','static const uint16_t f75_pet_palette[16]={'+','.join(hex(c) for c in rgb565)+'};','static const uint8_t f75_pet_sprites[6][2048]={']
for frame in packed:
 lines.append('{')
 lines.extend(','.join(f'0x{b:02x}' for b in frame[i:i+32])+',' for i in range(0,len(frame),32))
 lines.append('},')
lines.append('};')
# Compile the actual screen size directly from the original atlas. Do not
# enlarge the 64x64, 15-color compatibility sprites. Color zero is transparent;
# reserve 0001 for opaque pixels that quantize to black so outlines stay opaque.
assert all(rgb565[1:])
lines.append('static const uint16_t f75_pet_native[6][6400]={')
for frame in native_frames:
 native=[0 if a<128 else max(1,((r>>3)<<11)|((g>>2)<<5)|(b>>3)) for r,g,b,a in frame.get_flattened_data()]
 lines.append('{')
 lines.extend(','.join(f'0x{b:04x}' for b in native[i:i+16])+',' for i in range(0,len(native),16))
 lines.append('},')
lines.extend(['};','#endif'])
(ROOT/'firmware/pet_assets.h').write_text('\n'.join(lines)+'\n')
metadata={'source_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),'source':'AI-generated original character sprite atlas','grid':[3,2],'frame_size':[64,64],'frames':['idle','blink','type-left','type-right','cheer','sleep'],'palette_entries':16,'pixel_storage_bytes':6*2048,'palette_storage_bytes':32,'native_frame_size':[80,80],'native_rgb565_storage_bytes':6*80*80*2,'native_source':'original atlas at target size; RGB565, no 15-color palette','native_transparent_color':0,'native_opaque_black':1,'transparent_index':0,'compiler':'scripts/build_pet_assets.py'}
(ROOT/'assets/chibi/manifest.json').write_text(json.dumps(metadata,indent=2)+'\n')
print('Compiled six 64x64 packed sprites and six 80x80 RGB565 frames (76800 bytes in flash)')
