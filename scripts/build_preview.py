#!/usr/bin/env python3
"""Bundle the local preview scripts in dependency order without a build dependency."""
from pathlib import Path
root=Path(__file__).resolve().parents[1]
files=['engine.js','font.js','layout.js','app.js','native.js']
parts=['/* Generated by scripts/build_preview.py. Edit the source files, then rebuild. */']
for name in files:
    parts.extend(['\n/* '+name+' */\n',(root/'ui'/name).read_text(encoding='utf-8')])
(root/'ui/studio.js').write_text('\n'.join(parts)+'\n', encoding='utf-8', newline='\n')
print('Bundled '+str(len(files))+' preview source files')
