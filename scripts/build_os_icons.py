#!/usr/bin/env python3
"""Compile the pinned OS coverage masks for the board and browser editor."""
from pathlib import Path
import json,hashlib
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
icons=[];sources={}
for name in ['apple','windows','android']:
 path=ROOT/'assets/os-icons'/(name+'.png');im=Image.open(path).convert('L');assert im.size==(14,14)
 pixels=[(p*15+127)//255 for p in im.get_flattened_data()]
 icons.append({'name':name,'size':14,'pixels':pixels});sources[name]=hashlib.sha256(path.read_bytes()).hexdigest()
lines=['/* Generated by scripts/build_os_icons.py from pinned coverage masks. */','#pragma once','#include <stdint.h>','#define F75_OS_ICON_SIZE 14','static const uint8_t f75_os_icon_alpha[3][98]={']
for icon in icons:
 p=icon['pixels'];packed=[(p[i]<<4)|p[i+1] for i in range(0,len(p),2)]
 lines.append('{'+','.join(hex(p) for p in packed)+'},')
lines.append('};')
(ROOT/'firmware/f75_icons.h').write_text('\n'.join(lines)+'\n')
(ROOT/'ui/os-icons.js').write_text('// Generated by scripts/build_os_icons.py.\nwindow.F75_OS_ICONS='+json.dumps(icons,separators=(',',':'))+';\n')
(ROOT/'assets/os-icons/manifest.json').write_text(json.dumps({'size':14,'coverage_bits':4,'sources_sha256':sources,'compiler':'scripts/build_os_icons.py'},indent=2)+'\n')
