#!/usr/bin/env python3
"""Compile 48 native-size poses into bounded, palette-indexed LZ streams."""
from collections import defaultdict
import hashlib
import json
import zlib
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
NAMES = ['keyboard-dog', 'little-robot', 'anime-guy', 'starlight']


def compress(data):
    bits = []
    def emit(value, count):
        bits.extend((value >> bit) & 1 for bit in range(count))
    previous = defaultdict(list)
    position = 0
    while position < len(data):
        best = distance = 0
        if position + 3 <= len(data):
            for start in reversed(previous[data[position:position + 3]][-128:]):
                if position - start > 2048:
                    break
                length = 3
                while length < 34 and position + length < len(data) and data[start + length] == data[position + length]:
                    length += 1
                if length > best:
                    best, distance = length, position - start
                if best == 34:
                    break
        length = best if best >= 3 else 1
        if length == 1:
            emit(1, 1); emit(data[position], 6)
        else:
            emit(0, 1); emit(distance - 1, 11); emit(length - 3, 5)
        for offset in range(length):
            if position + offset + 3 <= len(data):
                previous[data[position + offset:position + offset + 3]].append(position + offset)
        position += length
    return bytes(sum(bits[at + bit] << bit for bit in range(min(8, len(bits) - at)))
                 for at in range(0, len(bits), 8))


def main():
    lines = ['/* Generated by scripts/build_companion_bank.py. */', '#ifndef F75_COMPANION_ASSETS_H',
             '#define F75_COMPANION_ASSETS_H', '#include <stdint.h>',
             '#define F75_COMPANION_COUNT 4', '#define F75_COMPANION_FRAMES 12']
    palettes, sizes, checks, checksums = [], [], [], []
    for character, name in enumerate(NAMES):
        folder = ROOT / f'ui/assets/characters/{name}'
        image = Image.open(folder / 'sprites-80.png').convert('RGBA')
        pixels = list(image.get_flattened_data())
        opaque = [p[:3] for p in pixels if p[3]]
        sample = Image.new('RGB', (len(opaque), 1)); sample.putdata(opaque)
        quantized = sample.quantize(colors=63, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
        colors = [tuple(quantized.getpalette()[i:i + 3]) for i in range(0, 189, 3)]
        palette_image = Image.new('P', (1, 1))
        palette_image.putpalette([v for color in colors + [colors[-1]] * 193 for v in color])
        indices = image.convert('RGB').quantize(palette=palette_image, dither=Image.Dither.NONE)
        lookup = {color: i for i, color in reversed(list(enumerate(colors)))}
        indices = [1 + lookup[colors[min(index, 62)]] if pixel[3] else 0
                   for index, pixel in zip(indices.get_flattened_data(), pixels)]
        palette = [0] + [max(1, (r >> 3) << 11 | (g >> 2) << 5 | b >> 3) for r, g, b in colors]
        palettes.append(palette)
        preview = Image.new('RGBA', image.size)
        preview.putdata([((palette[i] >> 11) * 255 // 31, ((palette[i] >> 5) & 63) * 255 // 63,
                          (palette[i] & 31) * 255 // 31, 255) if i else (0, 0, 0, 0) for i in indices])
        preview.save(folder / 'firmware-sprites-80.png')
        character_sizes = []
        character_checksums = []
        for frame in range(12):
            raw = bytes(value for row in range(80) for value in
                        indices[((frame // 3) * 80 + row) * 240 + (frame % 3) * 80:
                                ((frame // 3) * 80 + row) * 240 + (frame % 3) * 80 + 80])
            encoded = compress(raw)
            lines.append(f'static const uint8_t f75_companion_{character}_{frame}[]={{')
            lines.extend(','.join(f'0x{x:02x}' for x in encoded[i:i + 32]) + ',' for i in range(0, len(encoded), 32))
            lines.append('};')
            character_sizes.append(len(encoded))
            character_checksums.append(zlib.crc32(raw))
            checks.append(dict(character=character, frame=frame, decoded_sha256=hashlib.sha256(raw).hexdigest(), encoded_bytes=len(encoded)))
        sizes.append(character_sizes)
        checksums.append(character_checksums)
    lines.append('static const uint16_t f75_companion_palette[4][64]={')
    lines.extend('{' + ','.join(hex(c) for c in p) + '},' for p in palettes)
    lines.append('};')
    lines.append('static const uint8_t *const f75_companion_streams[4][12]={')
    lines.extend('{' + ','.join(f'f75_companion_{c}_{f}' for f in range(12)) + '},' for c in range(4))
    lines.append('};')
    lines.append('static const uint16_t f75_companion_lengths[4][12]={')
    lines.extend('{' + ','.join(map(str, row)) + '},' for row in sizes)
    lines.extend(['};','static const uint32_t f75_companion_checksums[4][12]={'])
    lines.extend('{' + ','.join(hex(c)+'u' for c in row) + '},' for row in checksums)
    lines.extend(['};', '#endif'])
    (ROOT / 'firmware/companion_assets.h').write_text('\n'.join(lines) + '\n')
    result = dict(characters=NAMES, frames=checks, palette_entries_per_character=64,
                  compressed_bytes=sum(map(sum, sizes)), decoded_frame_bytes=6400,
                  decoded_cache_bytes=4800, format='lsb-first: 1+6-bit literal; 0+11-bit distance-minus-one+5-bit length-minus-three')
    (ROOT / 'assets/characters/firmware-bank.json').write_text(json.dumps(result, indent=2) + '\n')
    print(f'Compiled 48 poses: {result["compressed_bytes"]} compressed bytes, 4800-byte cache')


if __name__ == '__main__':
    main()
