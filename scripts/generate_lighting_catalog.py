"""Generate the stable firmware lighting names from the shared app catalog."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    effects = json.loads((ROOT / 'ui/lighting-effects.json').read_text())
    assert [effect['id'] for effect in effects] == list(range(25))
    assert len({effect['name'] for effect in effects}) == len(effects)
    names = ', '.join(json.dumps(effect['name']) for effect in effects)
    content = ('/* Generated by scripts/generate_lighting_catalog.py. */\n'
               '#ifndef F75_LIGHTING_CATALOG_H\n#define F75_LIGHTING_CATALOG_H\n'
               f'enum {{ F75_LIGHT_EFFECT_COUNT = {len(effects)} }};\n'
               f'#define F75_LIGHT_EFFECT_NAMES {{{names}}}\n#endif\n')
    output = ROOT / 'firmware/f75_lighting_catalog.h'
    if args.check:
        if output.read_text() != content:
            raise SystemExit('Regenerate the lighting catalog with scripts/generate_lighting_catalog.py')
    else:
        output.write_text(content)


if __name__ == '__main__':
    main()
