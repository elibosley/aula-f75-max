"""Pack the generated sixteen-frame cat atlas for the native 20-pixel visitor."""
from pathlib import Path
import hashlib,json
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
def main():
 source=ROOT/'assets/characters/visiting-cat/source-atlas.png'
 image=Image.open(source).convert('RGBA')
 frames=[]
 for i in range(16):
  x,y=i%4,i//4
  cell=image.crop((x*image.width//4,y*image.height//4,(x+1)*image.width//4,(y+1)*image.height//4))
  frames.append(cell.resize((20,20),Image.Resampling.LANCZOS))
 opaque=[p[:3] for frame in frames for p in frame.get_flattened_data() if p[3]>=128]
 sample=Image.new('RGB',(len(opaque),1));sample.putdata(opaque)
 palette=sample.quantize(colors=7,method=Image.Quantize.MEDIANCUT,dither=Image.Dither.NONE).getpalette()[:21]
 palette_image=Image.new('P',(1,1));palette_image.putpalette(palette+[0]*(768-21))
 colors=[0]+[max(1,((palette[i]>>3)<<11)|((palette[i+1]>>2)<<5)|(palette[i+2]>>3)) for i in range(0,21,3)]+[0]*8
 streams=[];previews=[]
 for frame in frames:
  quantized=frame.convert('RGB').quantize(palette=palette_image,dither=Image.Dither.NONE)
  values=[min(index,6)+1 if pixel[3]>=128 else 0 for index,pixel in zip(quantized.get_flattened_data(),frame.get_flattened_data())]
  encoded=[];at=0
  while at<len(values):
   count=1
   while count<16 and at+count<len(values) and values[at+count]==values[at]:count+=1
   encoded.append(((count-1)<<4)|values[at]);at+=count
  streams.append(encoded)
  preview=Image.new('RGBA',(20,20));preview.putdata([((colors[v]>>11)*255//31,((colors[v]>>5)&63)*255//63,(colors[v]&31)*255//31,255) if v else (0,0,0,0) for v in values]);previews.append(preview)
 lines=['/* Generated by scripts/build_visitor_assets.py. */','#pragma once','#include <stdint.h>','static const uint16_t f75_visitor_palette[16]={'+','.join(hex(c) for c in colors)+'};']
 for i,data in enumerate(streams):lines.append('static const uint8_t f75_visitor_'+str(i)+'[]={'+','.join(hex(v) for v in data)+'};')
 lines.extend(['static const uint8_t *const f75_visitor_frames[16]={'+','.join('f75_visitor_'+str(i) for i in range(16))+'};','static const uint16_t f75_visitor_lengths[16]={'+','.join(str(len(s)) for s in streams)+'};'])
 (ROOT/'firmware/f75_visitor_assets.h').write_text('\n'.join(lines)+'\n')
 out=ROOT/'ui/assets/characters/visiting-cat';out.mkdir(parents=True,exist_ok=True)
 sheet=Image.new('RGBA',(80,80))
 for i,preview in enumerate(previews):sheet.paste(preview,((i%4)*20,(i//4)*20))
 sheet.save(out/'sprites-20.png')
 result=dict(frames=16,frame_size=[20,20],source_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),encoded_bytes=sum(map(len,streams)),palette_entries=8,format='high nibble count-minus-one; low nibble palette index; index zero transparent')
 (ROOT/'assets/characters/visiting-cat/firmware-bank.json').write_text(json.dumps(result,indent=2)+'\n');print(json.dumps(result))
if __name__=='__main__':main()
